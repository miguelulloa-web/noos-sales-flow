function createIsolatedTestDb(dbName) {
  const dbPath = path.join(TEST_DIR, dbName);
  if (fs.existsSync(dbPath)) {
    fs.unlinkSync(dbPath);
  }
  const db = new DatabaseSync(dbPath);
  initSchema(db);
  return { db, dbPath };
}

/**
 * Mock interactive TTY input stream for deterministic testing.
 */
class MockTtyInputStream extends PassThrough {
  constructor() {
    super();
    this.isTTY = true;
    this.isRaw = false;
    this.rawModeHistory = [];
  }

  setRawMode(val) {
    this.isRaw = Boolean(val);
    this.rawModeHistory.push(this.isRaw);
    return this;
  }
}

