  await t.test('8. Entrada interactiva de contraseña con TTY simulado (promptSecret)', async (st) => {
    await st.test('A. Entrada carácter a carácter (tecleo normal)', async () => {
      const mockInput = new MockTtyInputStream();
      const mockOutput = new PassThrough();
      let outputBuffer = '';
      mockOutput.on('data', (d) => { outputBuffer += d.toString(); });

      const secretPromise = promptSecret('Prompt: ', { input: mockInput, output: mockOutput });

      // Escribir carácter a carácter
      const chars = ['C', 'l', 'a', 'v', 'e', 'S', 'e', 'g', 'u', 'r', 'a', '1', '2', '3', '!', '\r'];
      for (const ch of chars) {
        mockInput.write(ch);
      }

      const result = await secretPromise;
      assert.equal(result, 'ClaveSegura123!');
      // Validar que la salida solo tiene máscara y prompt, nunca la clave en texto plano
      assert.equal(outputBuffer.includes('ClaveSegura123!'), false);
      assert.equal(outputBuffer.includes('Prompt: ***************\n'), true);
      assert.equal(mockInput.listenerCount('data'), 0, 'data listener must be cleaned up');
    });

    await st.test('B. Contraseña pegada como un único bloque', async () => {
      const mockInput = new MockTtyInputStream();
      const mockOutput = new PassThrough();
      let outputBuffer = '';
      mockOutput.on('data', (d) => { outputBuffer += d.toString(); });

      const secretPromise = promptSecret('Pass: ', { input: mockInput, output: mockOutput });

      // Pegado en bloque sin enter inicial, seguido de Enter
      mockInput.write('PastedPasswordInSingleBlock123!');
      mockInput.write('\n');

      const result = await secretPromise;
      assert.equal(result, 'PastedPasswordInSingleBlock123!');
      assert.equal(outputBuffer.includes('PastedPasswordInSingleBlock123!'), false);
      assert.equal(mockInput.listenerCount('data'), 0);
    });

    await st.test('C. Bloque pegado que incluye contraseña y Enter en un solo chunk', async () => {
      const mockInput = new MockTtyInputStream();
      const mockOutput = new PassThrough();
      let outputBuffer = '';
      mockOutput.on('data', (d) => { outputBuffer += d.toString(); });

      const secretPromise = promptSecret('Pass: ', { input: mockInput, output: mockOutput });

      // Un solo chunk con texto + \r\n
      mockInput.write('InstantPasteWithCRLF123!\r\n');

      const result = await secretPromise;
      assert.equal(result, 'InstantPasteWithCRLF123!');
      assert.equal(outputBuffer.includes('InstantPasteWithCRLF123!'), false);
      assert.equal(mockInput.listenerCount('data'), 0);
    });

    await st.test('D. Tratamiento correcto de Backspace', async () => {
      const mockInput = new MockTtyInputStream();
      const mockOutput = new PassThrough();
      let outputBuffer = '';
      mockOutput.on('data', (d) => { outputBuffer += d.toString(); });

      const secretPromise = promptSecret('Key: ', { input: mockInput, output: mockOutput });

      // Teclear 'a', 'b', 'c', borrar dos caracteres ('\b', '\b'), teclear 'd', luego Enter
      mockInput.write('a');
      mockInput.write('b');
      mockInput.write('c');
      mockInput.write('\b');
      mockInput.write('\u007f'); // backspace alternativo
      mockInput.write('d');
      mockInput.write('\n');

      const result = await secretPromise;
      assert.equal(result, 'ad');
      assert.equal(outputBuffer.includes('ad'), false);
      assert.equal(mockInput.listenerCount('data'), 0);
    });

    await st.test('E. Cancelación con Ctrl+C (rejection limpia, restauración de modo)', async () => {
      const mockInput = new MockTtyInputStream();
      const mockOutput = new PassThrough();
      let outputBuffer = '';
      mockOutput.on('data', (d) => { outputBuffer += d.toString(); });

      const secretPromise = promptSecret('Key: ', { input: mockInput, output: mockOutput });

      mockInput.write('some_partial');
      mockInput.write('\u0003'); // Ctrl+C

      await assert.rejects(async () => {
        await secretPromise;
      }, (err) => {
        assert.ok(err instanceof OperationCancelledError);
        assert.equal(err.isCancelled, true);
        return true;
      });

      assert.equal(outputBuffer.includes('some_partial'), false);
      assert.equal(mockInput.isRaw, false, 'Raw mode must be restored to false on Ctrl+C');
      assert.equal(mockInput.listenerCount('data'), 0);
    });

    await st.test('F. Error de stream durante la lectura (limpieza de listeners)', async () => {
      const mockInput = new MockTtyInputStream();
      const mockOutput = new PassThrough();

      const secretPromise = promptSecret('Key: ', { input: mockInput, output: mockOutput });

      mockInput.destroy(new Error('Simulated socket breakdown'));

      await assert.rejects(async () => {
        await secretPromise;
      }, /Simulated socket breakdown/);

      assert.equal(mockInput.listenerCount('data'), 0);
    });
  });

