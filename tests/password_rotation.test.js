  await t.test('1. Validación estricta de formato bcrypt (isValidBcryptHash)', async () => {
    // Generar un hash canónico real con bcryptjs
    const validCanonicalHash = await hashPassword('TestValidPassword123!');
    assert.equal(isValidBcryptHash(validCanonicalHash), true, 'Bcrypt hash generated by canonical module must be valid');

    // Hashes válidos con variantes estándar ($2a$, $2b$, $2y$) y longitud exacta 60
    assert.equal(isValidBcryptHash('$2a$10$N9qo8uLOickgx2ZMRZoMyeIjZAgcfl7p92ldGxad68LJZdL17lhWy'), true);
    assert.equal(isValidBcryptHash('$2b$12$N9qo8uLOickgx2ZMRZoMyeIjZAgcfl7p92ldGxad68LJZdL17lhWy'), true);
    assert.equal(isValidBcryptHash('$2y$10$N9qo8uLOickgx2ZMRZoMyeIjZAgcfl7p92ldGxad68LJZdL17lhWy'), true);

    // Casos negativos: cadenas arbitrarias, truncadas, incompletas o malformadas
    assert.equal(isValidBcryptHash(null), false);
    assert.equal(isValidBcryptHash(''), false);
    assert.equal(isValidBcryptHash('$2'), false);
    assert.equal(isValidBcryptHash('$2a$'), false);
    assert.equal(isValidBcryptHash('$2b$10$'), false);
    assert.equal(isValidBcryptHash('$2b$10$short'), false);
    assert.equal(isValidBcryptHash('$2b$10$N9qo8uLOickgx2ZMRZoMyeIjZAgcfl7p92ldGxad68LJZdL17lhWyEXTRA'), false);
    assert.equal(isValidBcryptHash('PlaintextPassword123!'), false);
    assert.equal(isValidBcryptHash('$3a$10$N9qo8uLOickgx2ZMRZoMyeIjZAgcfl7p92ldGxad68LJZdL17lhWy'), false);
  });

